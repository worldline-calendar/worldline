export interface Airport {
  code: string;
  city: string;
  zone: string;
}

export const AIRPORTS: ReadonlyMap<string, Airport> = new Map(
  Object.entries(BY_ZONE).flatMap(([zone, list]) =>
    list.split(',').map((x) => {
      const code = x.slice(0, 3);
      return [code, { code, city: x.slice(4), zone }] as const;
    }),
  ),
);

export const airport = (code: string | undefined): Airport | undefined => (code ? AIRPORTS.get(code.toUpperCase()) : undefined);
